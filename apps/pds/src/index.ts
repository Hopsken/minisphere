import { Hono } from "hono";
import { cors } from "hono/cors";
import { HTTPException } from "hono/http-exception";
import { logger } from "hono/logger";

import adminRoutes from "./routes/admin";
import xrpcRoutes from "./routes/xrpc";

const app = new Hono<{
  Bindings: Env;
}>();

app.use(cors()).use(logger());

app.get("/", (ctx) => ctx.json({ name: "pds" }));

app.route("/admin", adminRoutes);
app.route("/xrpc", xrpcRoutes);

// oxlint-disable-next-line promise/prefer-await-to-callbacks
app.onError((err, c) => {
  if (err instanceof HTTPException) {
    // Return the error response generated by HTTPException
    return err.getResponse();
  }

  // For any other unexpected errors, log and return a generic 500 response
  console.error(err);
  return c.text("Internal Server Error", 500);
});

export default app;

export { PdsDurableObject } from "./pds-do";
